export function getToolById(id: string): ToolMeta | undefined {
  return TOOLS.find((t) => t.id === id);
}

export function getCategoryById(id: string): CategoryMeta | undefined {
  return CATEGORIES.find((c) => c.id === id);
}

export function isValidToolId(id: string): id is ToolId {
  return TOOLS.some((t) => t.id === id);
}

export function searchTools(query: string, categoryFilter?: CategoryMeta['id'] | 'all'): ToolMeta[] {
  const normalized = query.trim().toLowerCase();
  return TOOLS.filter((tool) => {
    if (categoryFilter && categoryFilter !== 'all' && tool.category !== categoryFilter) {
      return false;
    }
    if (!normalized) return true;
    const haystack = [
      tool.nameAr,
      tool.nameEn,
      tool.shortDescAr,
      tool.fullDescAr,
      ...tool.keywords,
    ]
      .join(' ')
      .toLowerCase();
    return haystack.includes(normalized);
  });
}
